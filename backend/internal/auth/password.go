// Package auth 提供认证域原语：口令哈希/校验/长度策略、泄露口令筛查，
// 以及本包其余文件中的服务端会话与 CSRF 令牌。
//
// 口令存储遵循计划 GC-9：只存 argon2id 哈希。参数冻结于 security-03 §3.2
// 的 ARGON2ID_PARAMS（m=19456KiB, t=2, p=1）；keyLen=32 由 M1 计划 R-05
// 冻结——设计只给定 m/t/p，输出长度由实现计划显式裁决。
package auth

import (
	"crypto/rand"
	"crypto/sha1"
	"crypto/subtle"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/crypto/argon2"
)

const (
	// PWDMinLen / PWDMaxLen 是 F-01-01 的纯长度策略边界（security-01 §2.3）。
	// 策略不限制字符组成（TC-A-07 明确接受纯数字口令），也不做任何截断。
	PWDMinLen = 8
	PWDMaxLen = 128
)

const (
	// argon2id 成本参数：security-03 §3.2 冻结值（RFC 9106 内存受限基线）。
	// 19 MiB / 2 轮 / 单线程对登录路径约几十毫秒，显著高于 GPU 爆破的性价比门槛。
	argon2MemoryKiB = 19456
	argon2Time      = 2
	argon2Threads   = 1
	argon2KeyLen    = 32 // R-05：256-bit 输出
	argon2SaltLen   = 16 // 128-bit 随机盐，满足 security-03 MIN_ENTROPY_BITS

	// 校验侧参数窗口。哈希串来自数据库，可能损坏或被伪造；进入 argon2 前
	// 必须拒绝越界参数：m=4294967295 会触发数 TiB 分配，t=0/p=0 会让
	// x/crypto/argon2 直接 panic（伪造哈希不得变成 DoS）。
	//
	// 下限直接冻结为基线：M1 没有历史哈希，低于基线的合法哈希不存在，只可能
	// 是伪造/降级；上限留出余量，允许未来按 security-03「随算力调升」后仍能
	// 按旧哈希记录的参数完成校验。
	maxVerifyMemoryKiB = 256 << 10 // 256 MiB
	maxVerifyTime      = 10
	maxVerifyThreads   = 16
	minVerifyKeyLen    = argon2KeyLen // R-05 冻结 32B；更短的摘要只可能是伪造
	maxVerifyKeyLen    = 1024
	maxVerifySaltLen   = 1024
)

// HashPassword 用 argon2id 计算口令哈希，输出 PHC 字符串
// $argon2id$v=19$m=19456,t=2,p=1$<b64salt>$<b64hash>（无填充标准 base64）。
//
// PHC 自描述格式让成本参数随哈希一起存储：未来调高参数时旧哈希仍可按其
// 记录的值校验，无需一次性重算。盐每次从 crypto/rand 取 128 bit，保证同一
// 口令的两次哈希不同，避免跨用户相等性泄露与预计算表攻击。
func HashPassword(plain string) (string, error) {
	salt := make([]byte, argon2SaltLen)
	if _, err := rand.Read(salt); err != nil {
		return "", fmt.Errorf("auth: generate argon2id salt: %w", err)
	}
	key := argon2.IDKey([]byte(plain), salt, argon2Time, argon2MemoryKiB, argon2Threads, argon2KeyLen)
	return fmt.Sprintf(
		"$argon2id$v=%d$m=%d,t=%d,p=%d$%s$%s",
		argon2.Version,
		argon2MemoryKiB,
		argon2Time,
		argon2Threads,
		base64.RawStdEncoding.EncodeToString(salt),
		base64.RawStdEncoding.EncodeToString(key),
	), nil
}

// VerifyPassword 用 crypto/subtle 恒定时间比较口令与 PHC 哈希；畸形或伪造
// 的哈希一律返回 false，且不得 panic（security-01 §2.4：登录分支要对
// 不可信输入保持稳健）。
//
// 不截断、不做大小写或 Unicode 归一化（security-01 §2.3）：argon2 直接消费
// 原始字节，调用方必须原样传入用户输入——任何归一化都会改变口令语义。
func VerifyPassword(hash, plain string) bool {
	p, ok := parseArgon2idPHC(hash)
	if !ok {
		return false
	}
	// 输出长度取自已解析的哈希，再与同长度期望值恒定时间比较。
	derived := argon2.IDKey([]byte(plain), p.salt, p.time, p.memory, p.threads, uint32(len(p.key)))
	return subtle.ConstantTimeCompare(derived, p.key) == 1
}

type argon2idPHC struct {
	memory  uint32
	time    uint32
	threads uint8
	salt    []byte
	key     []byte
}

// parseArgon2idPHC 严格解析本系统产出的 PHC 形态。拒绝未知参数、重复参数、
// 填充式 base64 与越界成本，确保伪造输入永远到不了 argon2 内部。
func parseArgon2idPHC(encoded string) (argon2idPHC, bool) {
	parts := strings.Split(encoded, "$")
	if len(parts) != 6 || parts[0] != "" || parts[1] != "argon2id" {
		return argon2idPHC{}, false
	}

	version, found := strings.CutPrefix(parts[2], "v=")
	if !found {
		return argon2idPHC{}, false
	}
	v, err := strconv.ParseUint(version, 10, 32)
	if err != nil || v != uint64(argon2.Version) {
		// x/crypto/argon2 只实现版本 19；其它版本无法按相同语义校验。
		return argon2idPHC{}, false
	}

	memory, rounds, threads, ok := parseArgon2idParams(parts[3])
	if !ok {
		return argon2idPHC{}, false
	}

	salt, err := base64.RawStdEncoding.Strict().DecodeString(parts[4])
	if err != nil || len(salt) == 0 || len(salt) > maxVerifySaltLen {
		return argon2idPHC{}, false
	}
	key, err := base64.RawStdEncoding.Strict().DecodeString(parts[5])
	if err != nil || len(key) < minVerifyKeyLen || len(key) > maxVerifyKeyLen {
		return argon2idPHC{}, false
	}

	return argon2idPHC{memory: memory, time: rounds, threads: threads, salt: salt, key: key}, true
}

// parseArgon2idParams 解析 PHC 的 "m=..,t=..,p=.." 段并施加资源上界。
func parseArgon2idParams(s string) (memory, rounds uint32, threads uint8, ok bool) {
	var seenM, seenT, seenP bool
	for _, field := range strings.Split(s, ",") {
		name, value, found := strings.Cut(field, "=")
		if !found || value == "" {
			return 0, 0, 0, false
		}
		switch name {
		case "m":
			n, err := strconv.ParseUint(value, 10, 32)
			if err != nil || seenM {
				return 0, 0, 0, false
			}
			memory, seenM = uint32(n), true
		case "t":
			n, err := strconv.ParseUint(value, 10, 32)
			if err != nil || seenT {
				return 0, 0, 0, false
			}
			rounds, seenT = uint32(n), true
		case "p":
			n, err := strconv.ParseUint(value, 10, 8)
			if err != nil || seenP {
				return 0, 0, 0, false
			}
			threads, seenP = uint8(n), true
		default:
			return 0, 0, 0, false
		}
	}
	if !seenM || !seenT || !seenP {
		return 0, 0, 0, false
	}
	// 下限 = 冻结基线（m=19456, t=2, p=1）：M1 没有历史哈希，任何低于基线的
	// 参数只可能来自伪造/降级，必须拒绝。t≥1、p≥1 同时满足 argon2.IDKey 的
	// 前置条件（否则会 panic）。
	if rounds < argon2Time || rounds > maxVerifyTime ||
		threads < argon2Threads || threads > maxVerifyThreads ||
		memory < argon2MemoryKiB || memory > maxVerifyMemoryKiB {
		return 0, 0, 0, false
	}
	return memory, rounds, threads, true
}

// ValidatePasswordLength 实施 F-01-01 的纯长度策略：8–128 个字符，不限制
// 字符组成。计数口径在此冻结为 Unicode code point（Go 的 rune）：后端是
// 策略的唯一执行点。注意 JS 的 String.length 按 UTF-16 code unit 计数
// （emoji 等增补平面字符会算 2），前端表单（Task 15）必须用
// Array.from(v).length 对齐，避免前后端判定不一致。
//
// 空口令与超长口令在此拒绝；泄露筛查由 CompromisedPasswordChecker 独立
// 完成——长度合格但已泄露的口令仍须在注册/改密路径被拒（security-01 §2.3）。
func ValidatePasswordLength(plain string) bool {
	n := utf8.RuneCountInString(plain)
	return n >= PWDMinLen && n <= PWDMaxLen
}

// PwnedRangeFunc 取回 HIBP Pwned Passwords Range API 对某个 SHA-1 前缀的
// 响应体（每行 "<35 位十六进制后缀>:<次数>"）。由装配层注入生产实现；
// 测试注入内存假实现，绝不在测试中访问网络。
type PwnedRangeFunc func(prefix string) (string, error)

// CompromisedPasswordChecker 合并两类离线检查（security-01 §2.3）：
//  1. 随版本发布的 top-3000 高频口令表（ASVS 6.2.4）；
//  2. 站点/产品/用户上下文字词表，拦截 "NewTG2026" 这类可猜测口令。
//
// 零值即可使用（内置产品名词）。PwnedRange 非 nil 时额外启用 HIBP
// k-匿名查询：只发送 SHA-1(口令) 的前 5 位十六进制前缀，完整口令（乃至
// 完整摘要）永不离开进程（ASVS 6.2.12 / I7）。
type CompromisedPasswordChecker struct {
	// ContextWords 由部署方注入 site.title、部署域名/TLD 等站点级词。
	ContextWords []string
	// PwnedRange 为 nil 时完全不联网（默认关闭）；注入后启用可选 HIBP 查询。
	PwnedRange PwnedRangeFunc
}

// NewCompromisedPasswordChecker 构造带站点级上下文词的检查器。
func NewCompromisedPasswordChecker(contextWords ...string) CompromisedPasswordChecker {
	return CompromisedPasswordChecker{ContextWords: contextWords}
}

// Check 是安全设计冻结的接口签名，等价于不带每用户上下文的 CheckWithContext。
func (c CompromisedPasswordChecker) Check(plain string) bool {
	return c.CheckWithContext(plain)
}

// CheckWithContext 额外接受每用户上下文（如 username）：用户名无法预置在
// 站点级检查器里，只能在注册/改密的调用点传入。
func (c CompromisedPasswordChecker) CheckWithContext(plain string, contextWords ...string) bool {
	// 只有空口令可以提前退出：纯符号/emoji 口令归一化后为空，但仍是纯长度
	// 策略下的合法口令，启用 HIBP 时必须继续查询泄露库（TC-A-08）。
	if plain == "" {
		return false
	}
	compact := normalizePassword(plain)
	folded := foldLeet(plain)

	// 离线词表只在归一化结果非空时比对；top-3000 采用整串精确匹配，
	// 归一化只用于比对，不影响存储/校验。
	if compact != "" {
		if _, hit := commonPasswordSet[compact]; hit {
			return true
		}
		if folded != compact {
			if _, hit := commonPasswordSet[folded]; hit {
				return true
			}
		}

		words := make([]string, 0, len(builtinContextWords)+len(c.ContextWords)+len(contextWords))
		words = append(words, builtinContextWords...)
		words = append(words, c.ContextWords...)
		words = append(words, contextWords...)
		if containsContextWord(compact, folded, words) {
			return true
		}
	}

	if c.PwnedRange != nil {
		return c.pwned(plain)
	}
	return false
}

// builtinContextWords：产品名「NewTG」及站点产品名的连写形式——这两项与
// 部署无关，随代码冻结（security-01 §2.3）。site.title 与部署域名随实例
// 变化，由调用方通过 ContextWords 注入。
var builtinContextWords = []string{"newtg", "tokengateway"}

// minContextWordLen 防止过短的上下文（如单字母用户名）把几乎所有口令判为命中。
const minContextWordLen = 3

// containsContextWord 用「包含」而非整串相等来匹配上下文词，从而覆盖
// 追加数字/前缀等变体（"newtg2026"、"my-acme-pass"）。
func containsContextWord(compact, folded string, words []string) bool {
	for _, word := range words {
		w := normalizePassword(word)
		if utf8.RuneCountInString(w) < minContextWordLen {
			continue
		}
		if strings.Contains(compact, w) || strings.Contains(folded, w) {
			return true
		}
	}
	return false
}

// normalizePassword 生成仅用于词表比对的规范形：小写并去掉分隔符（空格、
// 标点）。它绝不参与哈希或校验——存储与校验始终消费原始字节（不归一化）。
func normalizePassword(plain string) string {
	var b strings.Builder
	b.Grow(len(plain))
	for _, r := range strings.ToLower(plain) {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// leetFold 把常见 leet 形变折叠回字母，覆盖 "p@ssw0rd"、"n3wtg" 这类口令
// （security-01 §2.3 要求处理 leet、大小写与追加数字）。必须直接作用于
// 原始输入：'@'、'$' 是字母替换而非分隔符，若先经 normalizePassword 剥除
// 就会把 "p@ssw0rd" 变成 "pssword" 而错过命中。折叠只影响词表比对，
// 不影响口令的真实哈希语义。
var leetFold = map[rune]rune{
	'0': 'o',
	'1': 'l',
	'2': 'z',
	'3': 'e',
	'4': 'a',
	'5': 's',
	'6': 'b',
	'7': 't',
	'8': 'b',
	'9': 'g',
	'@': 'a',
	'$': 's',
	'!': 'i',
	'+': 't',
}

// foldLeet 先做 leet 替换，再丢弃剩余的非字母数字字符（外壳中的分隔符）。
func foldLeet(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range strings.ToLower(s) {
		if repl, ok := leetFold[r]; ok {
			b.WriteRune(repl)
			continue
		}
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// pwned 查询 HIBP k-匿名接口。外部查询是可选增强（security-01 §2.3）：
// 故障时返回 false 回落到离线表——既不能把网络错误当成命中而拒绝所有
// 口令，也不应因外部服务不可用阻断注册。
func (c CompromisedPasswordChecker) pwned(plain string) bool {
	// SHA-1 仅作为 HIBP 查询键；口令存储仍是 argon2id（GC-9）。
	sum := sha1.Sum([]byte(plain))
	full := strings.ToUpper(hex.EncodeToString(sum[:]))

	body, err := c.PwnedRange(full[:5])
	if err != nil {
		return false
	}
	for _, line := range strings.Split(body, "\n") {
		suffix, count, ok := strings.Cut(strings.TrimSpace(line), ":")
		if !ok || !strings.EqualFold(suffix, full[5:]) {
			continue
		}
		// Add-Padding 响应会用 ":0" 填充不存在的后缀；0 次表示未泄露。
		n, err := strconv.Atoi(strings.TrimSpace(count))
		if err == nil && n == 0 {
			continue
		}
		return true
	}
	return false
}

// commonPasswordSet 由随版本发布的离线表构建（ASVS 6.2.4 / security-01
// §2.3 要求 ≥top-3000 且随版本发布，部署时无需联网）。条目按发布顺序取前
// 3000 条，并在构建时套用与输入相同的归一化，避免大小写/分隔符绕过。
var commonPasswordSet = func() map[string]struct{} {
	lines := strings.Split(commonPasswordsRaw, "\n")
	set := make(map[string]struct{}, len(lines))
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if norm := normalizePassword(line); norm != "" {
			set[norm] = struct{}{}
		}
	}
	return set
}()

